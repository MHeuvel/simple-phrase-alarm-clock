"""The sentence set, and rendering/merging of the sentence files.

No Home Assistant imports: this is plain Python plus PyYAML, so it can be
unit tested on its own.

There is ONE sentence set. It is written to two places:

* /config/custom_sentences/<language>/simple_phrase_alarm_clock.yaml
  Read by Assist (the conversation agent) to match text to our intents. This
  file is fully owned by the integration and is overwritten when it changes.

* /share/speech-to-phrase/custom_sentences/<language>/sentences.yaml
  Read by the Speech-to-Phrase add-on to train its speech recogniser. This
  file may also contain the user's own sentences, so our intents and lists
  are MERGED into it and everything else is left alone.
"""

from __future__ import annotations

import re
from typing import Any

import yaml

from .const import (
    INTENT_DELETE,
    INTENT_HIDE_LIST,
    INTENT_SET,
    INTENT_SET_REPEATING,
    INTENT_SHOW_LIST,
    LANGUAGE,
    SLOT_HOURS,
    SLOT_MINUTES,
    SLOT_REPEAT_MINUTES,
    SLOT_WEEKDAY,
)

_H = "{" + SLOT_HOURS + "}"
_M = "{" + SLOT_MINUTES + "}"
_RM = "{" + SLOT_REPEAT_MINUTES + "}"
_D = "{" + SLOT_WEEKDAY + "}"

# The complete phrase set. Zero-slot sentences cost one phrase each, so the
# list commands have two wordings.
SENTENCES: dict[str, list[str]] = {
    INTENT_SET: [
        f"set an alarm for {_H} hours {_M} minutes",
        f"set an alarm for {_H} hours",
    ],
    INTENT_SET_REPEATING: [
        f"set a repeating alarm for {_H} hours {_RM} minutes on {_D}",
        f"set a repeating alarm for {_H} hours on {_D}",
    ],
    INTENT_DELETE: [
        "delete the last alarm",
        f"delete the alarm for {_H} hours {_M} minutes",
        f"delete the alarm for {_H} hours",
    ],
    INTENT_SHOW_LIST: [
        "show the alarm list",
        "display all alarms",
    ],
    INTENT_HIDE_LIST: [
        "close the alarm list",
        "hide the alarms",
    ],
}

# Spoken weekday -> the number the kiosk uses (0 = Sunday).
WEEKDAY_VALUES: list[tuple[str, int]] = [
    ("monday", 1),
    ("tuesday", 2),
    ("wednesday", 3),
    ("thursday", 4),
    ("friday", 5),
    ("saturday", 6),
    ("sunday", 0),
]

LISTS: dict[str, dict[str, Any]] = {
    SLOT_HOURS: {"range": {"from": 0, "to": 23}},
    SLOT_MINUTES: {"range": {"from": 0, "to": 59}},
    # If Speech-to-Phrase cannot cope with the full set, change this to
    # steps of five: {"values": [{"in": str(m), "out": m} for m in range(0, 60, 5)]}
    SLOT_REPEAT_MINUTES: {"range": {"from": 0, "to": 59}},
    SLOT_WEEKDAY: {
        "values": [{"in": spoken, "out": number} for spoken, number in WEEKDAY_VALUES]
    },
}

HEADER = (
    "# Generated by the Simple Phrase alarm clock integration.\n"
    "# Do not edit: this file is overwritten when the integration changes it.\n"
)


def _list_size(name: str) -> int:
    definition = LISTS[name]
    if "range" in definition:
        return definition["range"]["to"] - definition["range"]["from"] + 1
    return len(definition["values"])


def phrase_count() -> int:
    """Return how many phrases the set expands to (for documentation/logs)."""
    total = 0
    for sentences in SENTENCES.values():
        for sentence in sentences:
            count = 1
            for slot in re.findall(r"\{(\w+)\}", sentence):
                count *= _list_size(slot)
            total += count
    return total


def build_data(language: str = LANGUAGE) -> dict[str, Any]:
    """Return the sentence set as a data structure."""
    return {
        "language": language,
        "intents": {
            name: {"data": [{"sentences": list(sentences)}]}
            for name, sentences in SENTENCES.items()
        },
        "lists": {name: dict(value) for name, value in LISTS.items()},
    }


def render_config_file(language: str = LANGUAGE) -> str:
    """Render the file Assist reads from /config/custom_sentences/<language>/."""
    lines = [HEADER.rstrip("\n"), f'language: "{language}"', "intents:"]
    for name, sentences in SENTENCES.items():
        lines.append(f"  {name}:")
        lines.append("    data:")
        lines.append("      - sentences:")
        lines.extend(f'          - "{sentence}"' for sentence in sentences)
    lines.append("lists:")
    for name, value in LISTS.items():
        lines.append(f"  {name}:")
        if "range" in value:
            lines.append("    range:")
            lines.append(f"      from: {value['range']['from']}")
            lines.append(f"      to: {value['range']['to']}")
        else:
            lines.append("    values:")
            for item in value["values"]:
                lines.append(f'      - in: "{item["in"]}"')
                lines.append(f"        out: {item['out']}")
    return "\n".join(lines) + "\n"


def _load(existing_text: str | None) -> dict[str, Any]:
    """Parse an existing sentences file. Empty file -> empty dict."""
    if existing_text is None or not existing_text.strip():
        return {}
    data = yaml.safe_load(existing_text)
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise ValueError("sentences file is not a YAML mapping")
    return data


def _dump(data: dict[str, Any]) -> str:
    return yaml.safe_dump(
        data,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
    )


def merge_into_share(existing_text: str | None, language: str = LANGUAGE) -> str:
    """Return the Speech-to-Phrase sentences.yaml with our set merged in.

    Everything that is not ours is preserved. Raises ValueError when the
    existing file is not a mapping (it is then not touched by the caller).
    """
    data = _load(existing_text)
    ours = build_data(language)

    data.setdefault("language", language)

    intents = data.get("intents")
    if intents is None:
        intents = {}
    if not isinstance(intents, dict):
        raise ValueError("'intents' is not a mapping")
    intents.update(ours["intents"])
    data["intents"] = intents

    lists = data.get("lists")
    if lists is None:
        lists = {}
    if not isinstance(lists, dict):
        raise ValueError("'lists' is not a mapping")
    lists.update(ours["lists"])
    data["lists"] = lists

    return _dump(data)


def strip_from_share(existing_text: str | None) -> str | None:
    """Return the file with our intents and lists removed, or None if unchanged."""
    data = _load(existing_text)
    changed = False

    intents = data.get("intents")
    if isinstance(intents, dict):
        for name in SENTENCES:
            if intents.pop(name, None) is not None:
                changed = True
        if not intents:
            data.pop("intents")

    lists = data.get("lists")
    if isinstance(lists, dict):
        for name in LISTS:
            if lists.pop(name, None) is not None:
                changed = True
        if not lists:
            data.pop("lists")

    if not changed:
        return None
    return _dump(data)
